    /// Ordered pairs, the way the migration DSL delivers them: Soli hashes are
    /// insertion-ordered, so a `serde_json` object (which sorts its keys) would
    /// not model the input faithfully.
    fn pairs(raw: Vec<(&str, serde_json::Value)>) -> Vec<(String, serde_json::Value)> {
        raw.into_iter().map(|(k, v)| (k.to_string(), v)).collect()
    }

