pub const ROUTES_MARKER: &str = "# --- soli generate auth --passkeys ---";

pub fn routes_snippet() -> String {
    format!(
        r#"
{ROUTES_MARKER}
get("/passkeys", "passkeys#index")
post("/passkeys/options", "passkeys#creation_options")
post("/passkeys", "passkeys#create")
delete("/passkeys/:id", "passkeys#destroy")
post("/passkeys/login/options", "passkey_sessions#request_options")
post("/passkeys/login", "passkey_sessions#create")
"#
    )
}

