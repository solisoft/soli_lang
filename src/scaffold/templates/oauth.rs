pub const ROUTES_MARKER: &str = "# --- soli generate oauth ---";

pub fn routes_snippet() -> String {
    format!(
        r#"
{ROUTES_MARKER}
get("/auth/:provider", "oauth#start")
get("/auth/:provider/callback", "oauth#callback")
"#
    )
}

/// Marker of the routes added with account linking and Apple's posted answer.
pub const LINKING_ROUTES_MARKER: &str = "# --- soli generate oauth: linking ---";

/// Routes of the actions a controller written before them does not have, so
/// they are appended only next to a controller that does.
pub fn linking_routes_snippet() -> String {
    format!(
        r#"
{LINKING_ROUTES_MARKER}
# Apple posts its answer from its own site; the action only turns that POST
# into a GET of the same URL, so the origin gate has nothing to protect here.
post("/auth/:provider/callback", "oauth#callback")
skip_csrf("/auth/apple/callback")
get("/oauth/identities", "oauth#identities")
delete("/oauth/identities/:id", "oauth#unlink")
"#
    )
}

/// Marker of the routes of the re-authentication step that guards linking.
pub const REAUTH_ROUTES_MARKER: &str = "# --- soli generate oauth: reauth ---";

/// Routes of `/oauth/reauth`, appended only next to a controller that has the
/// actions, like the linking ones.
pub fn reauth_routes_snippet() -> String {
    format!(
        r#"
{REAUTH_ROUTES_MARKER}
# Linking a provider needs a sign-in from the last ten minutes, or the password.
get("/oauth/reauth", "oauth#reauth")
post("/oauth/reauth", "oauth#reauthenticate")
"#
    )
}

/// Marker of the route that starts linking a provider to the signed-in
/// account.
pub const LINK_ROUTES_MARKER: &str = "# --- soli generate oauth: link ---";

/// The route of `oauth#link_provider`, appended only next to a controller that
/// has the action. Linking used to start from `GET /auth/:provider`, which any
/// site can make a signed-in browser send; it is a CSRF-checked POST now.
pub fn link_routes_snippet() -> String {
    format!(
        r#"
{LINK_ROUTES_MARKER}
# Linking a provider to the signed-in account: a CSRF-checked POST (the Connect
# buttons of /oauth/identities). GET /auth/:provider only ever signs a guest in.
post("/auth/:provider/link", "oauth#link_provider")
"#
    )
}

