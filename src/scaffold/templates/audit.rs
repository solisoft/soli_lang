//! Templates for `soli generate audit` — a log of who changed what, as a
//! concern any model includes.

pub const AUDITED_CONCERN: &str = include_str!("audit/audited_concern.sl");
pub const AUDIT_MODEL: &str = include_str!("audit/audit_model.sl");

const UNCHAINED: &str = "const AUDIT_CHAINED = false";

/// The `Audit` model, with its entries chained by hash or not.
pub fn audit_model(chained: bool) -> String {
    if chained {
        AUDIT_MODEL.replacen(UNCHAINED, "const AUDIT_CHAINED = true", 1)
    } else {
        AUDIT_MODEL.to_string()
    }
}

pub fn audits_migration(chained: bool) -> String {
    let chain_index = if chained {
        "  db.create_index(\"audits\", \"idx_audit_seq\", [\"seq\"], {\"unique\": true})\n"
    } else {
        ""
    };
    format!(
        r#"# Migration: create_audits
# Generated by: soli generate audit

def up(db)
  db.create_collection("audits")
  db.create_index("audits", "idx_audit_record", ["record_type", "record_key"], {{}})
  db.create_index("audits", "idx_audit_actor", ["actor_type", "actor_key"], {{}})
  db.create_index("audits", "idx_audit_at", ["at"], {{}})
{chain_index}end

def down(db)
  db.list_indexes("audits").each do |idx|
    db.drop_index("audits", idx["name"])
  end
  db.drop_collection("audits")
end
"#
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn the_chain_flag_sets_the_constant_and_the_unique_index() {
        assert!(AUDIT_MODEL.contains(UNCHAINED));
        assert!(audit_model(true).contains("const AUDIT_CHAINED = true"));
        assert!(!audit_model(true).contains(UNCHAINED));
        assert!(audits_migration(true).contains("idx_audit_seq"));
        assert!(!audits_migration(false).contains("idx_audit_seq"));
    }
}
