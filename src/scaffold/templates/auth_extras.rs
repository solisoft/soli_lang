//! `--api-tokens` and `--impersonation`.

pub const MAGIC_LINK_MODEL: &str = include_str!("auth_extras/magic_link_model.sl");
pub const MAGIC_LINKS_CONTROLLER: &str = include_str!("auth_extras/magic_links_controller.sl");
pub const MAGIC_LINK_MAILER: &str = include_str!("auth_extras/magic_link_mailer.sl");
pub const MAGIC_LINKS_NEW_VIEW: &str = include_str!("auth_extras/magic_links_new.html.slv");
pub const MAGIC_LINK_MAIL_VIEW: &str = include_str!("auth_extras/mailer_sign_in.html.slv");

pub const API_TOKEN_MODEL: &str = include_str!("auth_extras/api_token_model.sl");
pub const API_TOKEN_MIDDLEWARE: &str = include_str!("auth_extras/api_token_middleware.sl");
pub const API_TOKENS_CONTROLLER: &str = include_str!("auth_extras/api_tokens_controller.sl");
pub const API_TOKENS_INDEX_VIEW: &str = include_str!("auth_extras/api_tokens_index.html.slv");

pub const IMPERSONATIONS_CONTROLLER: &str =
    include_str!("auth_extras/impersonations_controller.sl");
pub const IMPERSONATION_HELPER: &str = include_str!("auth_extras/impersonation_helper.sl");
pub const IMPERSONATION_BANNER: &str = include_str!("auth_extras/impersonation_banner.html.slv");

pub const MAGIC_LINK_ROUTES_MARKER: &str = "# --- soli generate auth --magic-link ---";
pub const API_TOKENS_ROUTES_MARKER: &str = "# --- soli generate auth --api-tokens ---";
pub const IMPERSONATION_ROUTES_MARKER: &str = "# --- soli generate auth --impersonation ---";

pub fn magic_link_routes() -> String {
    format!(
        r#"
{MAGIC_LINK_ROUTES_MARKER}
get("/login/link", "magic_links#new")
post("/login/link", "magic_links#create")
get("/login/link/:token", "magic_links#show")
post("/login/link/:token", "magic_links#redeem")
"#
    )
}

pub fn api_tokens_routes() -> String {
    format!(
        r#"
{API_TOKENS_ROUTES_MARKER}
get("/api_tokens", "api_tokens#index")
post("/api_tokens", "api_tokens#create")
delete("/api_tokens/:id", "api_tokens#destroy")
"#
    )
}

pub fn impersonation_routes() -> String {
    format!(
        r#"
{IMPERSONATION_ROUTES_MARKER}
post("/impersonate/:id", "impersonations#create")
delete("/impersonate", "impersonations#destroy")
"#
    )
}

fn collection_migration(name: &str, flag: &str, indexes: &str) -> String {
    format!(
        r#"# Migration: create_{name}
# Generated by: soli generate auth {flag}

def up(db)
  db.create_collection("{name}")
{indexes}end

def down(db)
  db.list_indexes("{name}").each do |idx|
    db.drop_index("{name}", idx["name"])
  end
  db.drop_collection("{name}")
end
"#
    )
}

pub fn magic_links_migration() -> String {
    collection_migration(
        "magic_links",
        "--magic-link",
        "  db.create_index(\"magic_links\", \"idx_magic_link_token\", [\"token_digest\"], {\"unique\": true})\n  db.create_index(\"magic_links\", \"idx_magic_link_user_id\", [\"user_id\"], {})\n",
    )
}

pub fn api_tokens_migration() -> String {
    collection_migration(
        "api_tokens",
        "--api-tokens",
        "  db.create_index(\"api_tokens\", \"idx_api_token_digest\", [\"token_digest\"], {\"unique\": true})\n  db.create_index(\"api_tokens\", \"idx_api_token_user_id\", [\"user_id\"], {})\n",
    )
}
